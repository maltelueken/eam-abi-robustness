# LBA
# ---------------------------------------------------------------------------


@pytest.fixture(scope="module")
def lba_points():
    return _read_fixture("emc2_lba_pointwise.csv")


def test_lba_logpdf_matches_emc2_where_representable(lba_points):
    d = lba_points
    ours = np.array(
        lba_logpdf(
            jnp.array((d.rt - d.t0).to_numpy()),
            d.v_win.to_numpy(),
            d.sv_win.to_numpy(),
            d.A.to_numpy(),
            (d.A + d.B).to_numpy(),
        ),
    )
    ref = d.log_pdf.to_numpy()
    above_floor = ~np.isclose(ours, MIN_LL)
    well_conditioned = above_floor & (ours - MIN_LL > HEADROOM_NATS)
    near_floor = above_floor & ~well_conditioned

    assert well_conditioned.sum() > 300
    assert _relerr(ref[well_conditioned], ours[well_conditioned]).max() < 1e-8
    assert _relerr(ref[near_floor], ours[near_floor]).max() < NEAR_FLOOR_TOL


def test_lba_logpdf_floor_is_bounded_against_emc2(lba_points):
    # The complement of the test above: wherever our density has floored, EMC2's value must be
    # at or near the floor too. This is the regression test for the floor being applied to the
    # *density* -- flooring the pre-normalization bracket instead (as this once did) returned
    # `-log(A) - log Phi(v/s)` nats *above* the floor, i.e. a tail that was overstated rather
    # than clamped, and at A = 0.6, b = 1.8, v = 3.5, s = 1.2, dt = 0.05 that was -22.51
    # against a true value of e^-146.
    d = lba_points
    ours = np.array(
        lba_logpdf(
            jnp.array((d.rt - d.t0).to_numpy()),
            d.v_win.to_numpy(),
            d.sv_win.to_numpy(),
            d.A.to_numpy(),
            (d.A + d.B).to_numpy(),
        ),
    )
    floored = np.isclose(ours, MIN_LL)
    assert floored.any()
    assert np.all(ours[floored] == pytest.approx(MIN_LL))
    assert (d.log_pdf.to_numpy()[floored] - MIN_LL).max() < FLOOR_BAND_NATS


def test_lba_logsf_matches_emc2(lba_points):
    d = lba_points
    ours = np.array(
        lba_logsf(
            jnp.array((d.rt - d.t0).to_numpy()),
            d.v_lose.to_numpy(),
            d.sv_lose.to_numpy(),
            d.A.to_numpy(),
            (d.A + d.B).to_numpy(),
        ),
    )
    # No tiering needed here: unlike the Wald survival, the LBA's truncated-normal drift leaves
    # a heavy tail, so EMC2's `1 - plba(...)` stays well conditioned across the whole fixture.
    assert _relerr(d.log_sf.to_numpy(), ours).max() < 1e-8


def test_lba_race_logpdf_matches_emc2(lba_points):
    d = lba_points
    ours = np.array(
        lba_race_logpdf(
            jnp.array(d.rt.to_numpy()),
            d.v_win.to_numpy(),
            d.v_lose.to_numpy(),
            d.sv_win.to_numpy(),
            d.sv_lose.to_numpy(),
            d.A.to_numpy(),
            d.B.to_numpy(),
            d.t0.to_numpy(),
        ),
    )
    ref = np.maximum(d.log_race.to_numpy(), MIN_LL)
    floored = np.isclose(ours, MIN_LL)
    well_conditioned = ~floored & (ours - MIN_LL > HEADROOM_NATS)
    near_floor = ~floored & ~well_conditioned

    assert _relerr(ref[well_conditioned], ours[well_conditioned]).max() < 1e-8
    assert _relerr(ref[near_floor], ours[near_floor]).max() < NEAR_FLOOR_TOL
    # Same band as the pointwise density: where we floor, EMC2 must be near the floor as well.
    assert (ref[floored] - MIN_LL).max() < FLOOR_BAND_NATS


def test_lba_total_log_likelihood_matches_emc2():
    truth = _read_header_params("emc2_lba_dataset.csv")
